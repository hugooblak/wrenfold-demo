<h2 class="wp-block-heading" id="kitchens">Fitted kitchens</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>A kitchen from us is made to the room, not ordered from a size chart. That matters most in old houses, where no wall is straight and no ceiling is level. We measure once at the start and again after the plastering, then cut to the second set of numbers.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>A typical kitchen is six to ten weeks from the day you sign the drawing. Two of those weeks are paint drying, so the timing is hard to rush.</p>
