<h2 class="wp-block-heading" id="staircases">Stairs and handrails</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Staircases are the job where guessing costs the most. We make a full-size template on site, take it back to the bench and cut the strings against it. The treads then meet the wall on their own, with no packing pieces hidden behind the skirting.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>We do straight flights, quarter and half landings, winders, and handrails on their own where the stairs are staying. Building regulations set the rise, the going and the handrail height, and we work to them rather than around them.</p>
<!-- /wp:paragraph -->
</div>
